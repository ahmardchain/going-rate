// Generates data/seed-pool.json: demo data, clearly labelled seeded: true.
// Deterministic (fixed RNG seed) so the demo and tests are reproducible.
// These are NOT real Kite approvals. They stand in for a pool until real
// outcomes (from `kpass activity` and Going Rate itself) accumulate.
import { writeFileSync } from "node:fs";

let s = 20261102;
const rand = () => ((s = (s * 1664525 + 1013904223) % 4294967296) / 4294967296);
const jitter = (base, spread) => base * Math.exp((rand() * 2 - 1) * spread); // log-uniform noise
const cents = (v) => Math.max(0.01, Math.round(v * 100) / 100);

const TYPES = {
  "data-api-lookup": { perTx: 0.05, total: 2, ttl: 4, summaries: ["Fetch hourly weather for 12 cities", "Pull FX spot rates for a pricing report", "Look up company news for a briefing", "Geocode 200 delivery addresses", "Run 50 web search queries for research"] },
  "llm-inference": { perTx: 0.25, total: 5, ttl: 6, summaries: ["Summarise 40 support tickets", "Translate product docs to Spanish", "Embed a 2k-document knowledge base", "Draft replies to 30 customer emails"] },
  "image-generation": { perTx: 0.5, total: 5, ttl: 2, summaries: ["Generate 10 product thumbnails", "Create a logo concept set", "Make header images for 8 blog posts", "Render 12 social media illustrations"] },
  "audio-generation": { perTx: 0.4, total: 4, ttl: 3, summaries: ["Voiceover for a 3-minute explainer", "Transcribe 6 meeting recordings", "Text-to-speech for 20 short clips"] },
  "video-generation": { perTx: 2.5, total: 20, ttl: 6, summaries: ["Generate a 30-second product teaser", "Create 5 short video ads", "Edit and caption a demo video"] },
  "web-scraping": { perTx: 0.1, total: 8, ttl: 12, summaries: ["Crawl 500 competitor product pages", "Scrape job listings from 30 sites", "Extract prices from 1,000 listings"] },
  "cloud-compute": { perTx: 5, total: 40, ttl: 24, summaries: ["Run a GPU fine-tuning job", "Provision a prepaid cloud project for a deploy", "Batch-render 3D scenes on GPUs"] },
  "other": { perTx: 1, total: 5, ttl: 4, summaries: ["Pay a bounty for a bug report", "Buy a dataset license"] },
};

const rows = [];
let id = 0;
const day = (n) => new Date(Date.UTC(2026, 9, 1 + n, 9 + (n % 9))).toISOString();
for (const [type, t] of Object.entries(TYPES)) {
  const nApproved = 8 + Math.floor(rand() * 4);
  for (let i = 0; i < nApproved; i++) {
    const total = cents(jitter(t.total, 0.45));
    rows.push({ id: `seed-${++id}`, task_type: type, task_summary: t.summaries[i % t.summaries.length],
      per_tx_usd: Math.min(cents(jitter(t.perTx, 0.4)), total), total_usd: total,
      ttl_hours: Math.max(1, Math.round(jitter(t.ttl, 0.4))), outcome: "approved",
      source: "seed", seeded: true, at: day(Math.floor(rand() * 40)) });
  }
  const nRejected = 2 + Math.floor(rand() * 2);
  for (let i = 0; i < nRejected; i++) {
    const total = cents(t.total * (6 + rand() * 20)); // wild asks are the ones that get rejected
    rows.push({ id: `seed-${++id}`, task_type: type, task_summary: t.summaries[(i + 1) % t.summaries.length],
      per_tx_usd: Math.min(cents(t.perTx * (5 + rand() * 40)), total), total_usd: total,
      ttl_hours: 24 * (1 + Math.floor(rand() * 7)), outcome: "rejected",
      source: "seed", seeded: true, at: day(Math.floor(rand() * 40)) });
  }
}
rows.sort((a, b) => a.at.localeCompare(b.at));
writeFileSync(new URL("../data/seed-pool.json", import.meta.url), JSON.stringify({
  note: "SEEDED DEMO DATA. Not real Kite approvals. Generated by scripts/make-seed.js.",
  records: rows,
}, null, 1) + "\n");
console.log(`wrote ${rows.length} seeded records`);
